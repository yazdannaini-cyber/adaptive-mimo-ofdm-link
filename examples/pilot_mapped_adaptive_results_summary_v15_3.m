function summary = pilot_mapped_adaptive_results_summary_v15_3(results)
%PILOT_MAPPED_ADAPTIVE_RESULTS_SUMMARY_V15_3 Summarize joint link adaptation.
required={'Channel','Strategy','CodingMode','PayloadBER','CodedBER','PacketErrorRate', ...
 'FrameErrorRate','MeanNetPayloadSE_bpsHz','MeanGrossSE_bpsHz','MeanCRCGoodput_bpsHz', ...
 'CRCGoodput_FrameBootstrapCI95_Lower','CRCGoodput_FrameBootstrapCI95_Upper', ...
 'PayloadBER_FrameBootstrapCI95_Upper','PER_FrameBootstrapCI95_Upper', ...
 'MeanPosteriorPredictedPER','WorstPosteriorPredictedPERU95','TargetPERFeasibleDataRatio', ...
 'MeanPredictedBER','FECDataRatio','NumFrames'};
if nargin<1||isempty(results)||~istable(results)||~all(ismember(required,results.Properties.VariableNames))
    error('pilot_mapped_adaptive_results_summary_v15_3:InvalidResults', ...
        'Pass the table returned by pilot_mapped_adaptive_validation_run_v15_3.');
end
channels=unique(string(results.Channel),'stable');
strategies=unique(string(results.Strategy),'stable');
codingModes=unique(string(results.CodingMode),'stable');
summary=[];
fprintf('\n============================================================\n');
fprintf('V15.3 JOINT ADAPTIVE MIMO/MODULATION/FEC RESULTS: %d rows\n',height(results));
fprintf('============================================================\n');
for c=1:numel(channels)
 for s=1:numel(strategies)
  for m=1:numel(codingModes)
   mask=string(results.Channel)==channels(c)&string(results.Strategy)==strategies(s)& ...
        string(results.CodingMode)==codingModes(m);
   if ~any(mask), continue; end
   payloadErrors=sum(results.TotalPayloadBitErrors(mask));
   payloadBits=sum(results.TotalPayloadBits(mask));
   codedErrors=sum(results.TotalCodedBitErrors(mask));
   codedBits=sum(results.TotalCodedBits(mask));
   packetErrors=sum(results.TotalPacketErrors(mask));
   packets=sum(results.TotalPackets(mask));
   aggregateBER=payloadErrors/max(payloadBits,1);
   aggregateCodedBER=codedErrors/max(codedBits,1);
   aggregatePER=packetErrors/max(packets,1);
   meanCRCGoodput=mean(results.MeanCRCGoodput_bpsHz(mask));
   worstCRCGoodputLower=min(results.CRCGoodput_FrameBootstrapCI95_Lower(mask));
   worstBERUpper=max(results.PayloadBER_FrameBootstrapCI95_Upper(mask));
   worstPERUpper=max(results.PER_FrameBootstrapCI95_Upper(mask));
   meanPredictedPER=mean(results.MeanPosteriorPredictedPER(mask),'omitnan');
   meanTargetFeasible=mean(results.TargetPERFeasibleDataRatio(mask),'omitnan');
   meanFEC=mean(results.FECDataRatio(mask));
   fprintf(['%-8s | %-21s | %-14s | payloadBER=%8.4g | codedBER=%8.4g | PER=%7.4f | FER=%7.4f\n' ...
     '         | netSE=%5.2f | bitGoodput=%5.2f | CRC-goodput=%5.2f [worst-L95=%5.2f] | FEC=%5.1f%%\n' ...
     '         | predPER=%7.4g | worst predPER U95=%7.4g | target-feasible=%5.1f%%\n'], ...
     char(channels(c)),char(strategies(s)),char(codingModes(m)),aggregateBER,aggregateCodedBER, ...
     aggregatePER,mean(results.FrameErrorRate(mask)),mean(results.MeanNetPayloadSE_bpsHz(mask)), ...
     mean(results.MeanBitGoodput_bpsHz(mask)),meanCRCGoodput,worstCRCGoodputLower, ...
     100*meanFEC,meanPredictedPER,max(results.WorstPosteriorPredictedPERU95(mask),[],'omitnan'), ...
     100*meanTargetFeasible);
   row=table(channels(c),strategies(s),codingModes(m),aggregateBER,aggregateCodedBER,aggregatePER, ...
      mean(results.FrameErrorRate(mask)),mean(results.MeanNetPayloadSE_bpsHz(mask)), ...
      mean(results.MeanGrossSE_bpsHz(mask)),mean(results.MeanBitGoodput_bpsHz(mask)), ...
      meanCRCGoodput,worstCRCGoodputLower,worstBERUpper,worstPERUpper,meanPredictedPER, ...
      meanTargetFeasible,meanFEC,payloadErrors,payloadBits,codedErrors,codedBits,packetErrors,packets, ...
      'VariableNames',{'Channel','Strategy','CodingMode','AggregatePayloadBER','AggregateCodedBER', ...
      'AggregatePER','MeanFER','MeanNetPayloadSE_bpsHz','MeanGrossSE_bpsHz','MeanBitGoodput_bpsHz', ...
      'MeanCRCGoodput_bpsHz','WorstConditionCRCGoodputL95','WorstConditionPayloadBERU95', ...
      'WorstConditionPERU95','MeanPosteriorPredictedPER','TargetPERFeasibleDataRatio', ...
      'FECDataRatio','PayloadBitErrors','PayloadBits','CodedBitErrors','CodedBits','PacketErrors','Packets'});
   if isempty(summary), summary=row; else, summary=[summary;row]; end %#ok<AGROW>
  end
 end
end

fprintf('\n--- Joint-adaptive mode, modulation and FEC decisions by channel/SNR ---\n');
for c=1:numel(channels)
 snrs=unique(results.PilotSNR_dB(string(results.Channel)==channels(c)));
 for q=1:numel(snrs)
  mask=string(results.Channel)==channels(c)&string(results.Strategy)=='joint-adaptive'& ...
       results.PilotSNR_dB==snrs(q);
  if ~any(mask), continue; end
  fprintf('%-8s | SNR=%2g dB | PER=%7.4f | CRC-goodput=%5.2f | SM=%4.0f%% | QAM16=%4.0f%% | FEC=%4.0f%% | PER-feasible=%4.0f%%\n', ...
      char(channels(c)),snrs(q),mean(results.PacketErrorRate(mask)), ...
      mean(results.MeanCRCGoodput_bpsHz(mask)),100*mean(results.SpatialMultiplexingDataRatio(mask)), ...
      100*mean(results.QAM16DataRatio(mask)),100*mean(results.FECDataRatio(mask)), ...
      100*mean(results.TargetPERFeasibleDataRatio(mask)));
 end
end
fprintf(['\nController note: the link-model PER is an initialization prior only. ' ...
 'The joint controller updates a per-action Beta-style estimate using only CRC ACK/NACK ' ...
 'outcomes from previously completed bursts. Target feasibility uses a one-sided 95%% ' ...
 'upper bound on this posterior estimate; when no action is feasible, the controller ' ...
 'falls back to the maximum posterior expected CRC-goodput action and marks it infeasible.\n']);
end
