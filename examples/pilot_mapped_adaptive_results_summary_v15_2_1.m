function summary = pilot_mapped_adaptive_results_summary_v15_2_1(results)
%PILOT_MAPPED_ADAPTIVE_RESULTS_SUMMARY_V15_2 Summarize BER, PER and CRC goodput.
required={'Channel','Strategy','CodingMode','FECDecoder','PayloadBER','CodedBER','PacketErrorRate', ...
 'FrameErrorRate','MeanNetPayloadSE_bpsHz','MeanGrossSE_bpsHz','MeanCRCGoodput_bpsHz', ...
 'CRCGoodput_FrameBootstrapCI95_Lower','CRCGoodput_FrameBootstrapCI95_Upper', ...
 'PayloadBER_WilsonCI95_Upper','PayloadBER_FrameBootstrapCI95_Upper', ...
 'PER_WilsonCI95_Upper','PER_FrameBootstrapCI95_Upper','MeanPredictedBER','NumFrames'};
if nargin<1||isempty(results)||~istable(results)||~all(ismember(required,results.Properties.VariableNames))
 error('pilot_mapped_adaptive_results_summary_v15_2_1:InvalidResults', ...
  'Pass the table returned by pilot_mapped_adaptive_validation_run_v15_2_1.');
end
channels=unique(string(results.Channel),'stable');
strategies=unique(string(results.Strategy),'stable');
codingModes=unique(string(results.CodingMode),'stable');
summary=[];
fprintf('\n============================================================\n');
fprintf('V15.2.1 SOFT-DECISION + PACKET-LEVEL RESULTS: %d rows\n',height(results));
fprintf('============================================================\n');
fprintf('QAM demapper: max-log soft LLR | FEC: soft-decision Viterbi for coded profile\n');
for c=1:numel(channels)
 for s=1:numel(strategies)
  for m=1:numel(codingModes)
   mask=string(results.Channel)==channels(c)&string(results.Strategy)==strategies(s)& ...
        string(results.CodingMode)==codingModes(m);
   if ~any(mask),continue;end
   payloadErrors=sum(results.TotalPayloadBitErrors(mask));
   payloadBits=sum(results.TotalPayloadBits(mask));
   codedErrors=sum(results.TotalCodedBitErrors(mask));
   codedBits=sum(results.TotalCodedBits(mask));
   packetErrors=sum(results.TotalPacketErrors(mask));
   packets=sum(results.TotalPackets(mask));
   aggBER=payloadErrors/max(payloadBits,1);
   aggCodedBER=codedErrors/max(codedBits,1);
   aggPER=packetErrors/max(packets,1);
   meanFER=mean(results.FrameErrorRate(mask));
   meanNetSE=mean(results.MeanNetPayloadSE_bpsHz(mask));
   meanGrossSE=mean(results.MeanGrossSE_bpsHz(mask));
   meanBitGoodput=mean(results.MeanBitGoodput_bpsHz(mask));
   meanCRCGoodput=mean(results.MeanCRCGoodput_bpsHz(mask));
   minCRCgoodputCI=min(results.CRCGoodput_FrameBootstrapCI95_Lower(mask));
   minBERupper=max(results.PayloadBER_FrameBootstrapCI95_Upper(mask));
   maxPERupper=max(results.PER_FrameBootstrapCI95_Upper(mask));
   meanPred=mean(results.MeanPredictedBER(mask));
   decoderName=string(results.FECDecoder(find(mask,1,'first')));
   fprintf('         | decoder: %s\n',char(decoderName));
   fprintf(['%-8s | %-21s | %-14s | payloadBER=%8.4g | codedBER=%8.4g | PER=%7.4f | FER=%7.4f\n' ...
     '         | payloadSE=%5.2f (gross=%5.2f) | bitGoodput=%5.2f | CRC-goodput=%5.2f [worst-L95=%5.2f]\n' ...
     '         | max U95 payloadBER(cluster)=%7.4g | max U95 PER(cluster)=%7.4g | predBER=%7.4g\n'], ...
     char(channels(c)),char(strategies(s)),char(codingModes(m)),aggBER,aggCodedBER,aggPER,meanFER, ...
     meanNetSE,meanGrossSE,meanBitGoodput,meanCRCGoodput,minCRCgoodputCI, ...
     minBERupper,maxPERupper,meanPred);
   row=table(channels(c),strategies(s),codingModes(m),decoderName,aggBER,aggCodedBER,aggPER,meanFER, ...
      meanNetSE,meanGrossSE,meanBitGoodput,meanCRCGoodput,minCRCgoodputCI,minBERupper, ...
      maxPERupper,meanPred,payloadErrors,payloadBits,codedErrors,codedBits,packetErrors,packets, ...
      'VariableNames',{'Channel','Strategy','CodingMode','FECDecoder','AggregatePayloadBER','AggregateCodedBER', ...
      'AggregatePER','MeanFER','MeanNetPayloadSE_bpsHz','MeanGrossSE_bpsHz', ...
      'MeanBitGoodput_bpsHz','MeanCRCGoodput_bpsHz','WorstConditionCRCGoodputL95', ...
      'WorstConditionPayloadBERU95','WorstConditionPERU95','MeanPredictedBER', ...
      'PayloadBitErrors','PayloadBits','CodedBitErrors','CodedBits','PacketErrors','Packets'});
   if isempty(summary),summary=row;else,summary=[summary;row];end %#ok<AGROW>
  end
 end
end
fprintf('\n--- By channel and pilot/data SNR: adaptive strategy ---\n');
for c=1:numel(channels)
 snrs=unique(results.PilotSNR_dB(string(results.Channel)==channels(c)));
 for m=1:numel(codingModes)
  for q=1:numel(snrs)
   mask=string(results.Channel)==channels(c)&string(results.Strategy)=='adaptive'& ...
       string(results.CodingMode)==codingModes(m)&results.PilotSNR_dB==snrs(q);
   if ~any(mask),continue;end
   fprintf('%-8s | SNR=%2g dB | %-14s | payloadBER=%7.4g | PER=%7.4g | CRC-goodput=%5.2f | SM=%4.0f%% | QAM16=%4.0f%%\n', ...
      char(channels(c)),snrs(q),char(codingModes(m)),mean(results.PayloadBER(mask)), ...
      mean(results.PacketErrorRate(mask)),mean(results.MeanCRCGoodput_bpsHz(mask)), ...
      100*mean(results.SpatialMultiplexingDataRatio(mask)),100*mean(results.QAM16DataRatio(mask)));
  end
 end
end
fprintf(['\nInterpretation: PayloadBER is post-decoder payload BER; CodedBER is hard-demapper BER ' ...
 'before Viterbi decoding. PER is measured from actual CRC checks on each burst packet. ' ...
 'CRC-goodput counts only payload bits from CRC-accepted packets. Cluster-bootstrap intervals ' ...
 'resample whole frames; Wilson intervals are bit/packet-IID references and may be optimistic ' ...
 'when errors cluster within fading frames.\n']);
end
