function results = pilot_mapped_adaptive_validation_run_v15_2_1(options)
%PILOT_MAPPED_ADAPTIVE_VALIDATION_RUN_V15_2 Statistical and packet-level study.
% Default 100 frames/condition. Use options.numFrames for a shorter smoke run.
% Each adaptive/fixed strategy is evaluated with uncoded CRC and rate-1/2
% convolutional FEC + CRC using paired channel/pilot/noise realizations.
if nargin<1, options=struct(); end
if ~isstruct(options), error('pilot_mapped_adaptive_validation_run_v15_2_1:Options','options must be a struct.'); end
projectRoot=fileparts(fileparts(mfilename('fullpath')));
addpath(genpath(projectRoot));
cfg=default_config(); cfg.channel.doppler.numOscillators=32;
channelNames={'rayleigh','rician'};
profileNames={'iid','joint-high'}; profileRhos=[0 0;0.9 0.9];
dopplerValuesHz=[0 120 300]; pilotSNRValuesdB=[8 14 20];
pilotSpacing=8; nSymbols=24; modulations=[4 16]; targetBER=1e-2;
numFrames=100; numBootstrap=2000; confidenceLevel=0.95;
if isfield(options,'numFrames'), numFrames=options.numFrames; end
if isfield(options,'numBootstrap'), numBootstrap=options.numBootstrap; end
if isfield(options,'targetBER'), targetBER=options.targetBER; end
if ~isscalar(numFrames)||~isfinite(numFrames)||numFrames<1||numFrames~=floor(numFrames)
    error('pilot_mapped_adaptive_validation_run_v15_2_1:NumFrames','numFrames must be a positive integer.');
end
if ~isscalar(numBootstrap)||~isfinite(numBootstrap)||numBootstrap<200||numBootstrap~=floor(numBootstrap)
    error('pilot_mapped_adaptive_validation_run_v15_2_1:Bootstrap','numBootstrap must be an integer >=200.');
end
if numFrames<30
    warning('pilot_mapped_adaptive_validation_run_v15_2_1:LowFrameCount', ...
        'Fewer than 30 frames is a screening run, not a strong frame-cluster validation.');
end
strategyNames={'adaptive','fixed-sm-16qam','fixed-alamouti-qpsk'};
codingModes={'uncoded-crc','conv-crc-1/2'};
numCandidates=numel(strategyNames)*numel(codingModes);
conditionCount=numel(channelNames)*numel(profileNames)*numel(dopplerValuesHz)*numel(pilotSNRValuesdB);
results=[]; frameLogParts=cell(conditionCount,1); blockLogParts=cell(conditionCount,1);
conditionNumber=0; oldRng=rng; restoreRng=onCleanup(@()rng(oldRng)); %#ok<NASGU>

for c=1:numel(channelNames)
 for p=1:numel(profileNames)
  for d=1:numel(dopplerValuesHz)
   for is=1:numel(pilotSNRValuesdB)
    conditionNumber=conditionNumber+1;
    channelName=channelNames{c}; profileName=profileNames{p};
    fd=dopplerValuesHz(d); snrDb=pilotSNRValuesdB(is);
    fprintf('\n[%d/%d] %s | %s | fD=%g Hz | pilot SNR=%g dB | frames=%d\n', ...
        conditionNumber,conditionCount,upper(channelName),profileName,fd,snrDb,numFrames);

    payloadErrors=zeros(numFrames,numCandidates); payloadBits=zeros(numFrames,numCandidates);
    codedErrors=zeros(numFrames,numCandidates); codedBits=zeros(numFrames,numCandidates);
    packetErrors=zeros(numFrames,numCandidates); packetCounts=zeros(numFrames,numCandidates);
    frameErrors=false(numFrames,numCandidates); frameGoodput=zeros(numFrames,numCandidates);
    frameBitGoodput=zeros(numFrames,numCandidates); frameNetSE=zeros(numFrames,numCandidates);
    frameGrossSE=zeros(numFrames,numCandidates); framePred=zeros(numFrames,numCandidates);
    frameFeasible=zeros(numFrames,numCandidates); frameSM=zeros(numFrames,numCandidates);
    frameAL=zeros(numFrames,numCandidates); frameQPSK=zeros(numFrames,numCandidates);
    frameQAM16=zeros(numFrames,numCandidates); framePost=zeros(numFrames,numCandidates);
    frameICI=zeros(numFrames,numCandidates); frameNMSE=zeros(numFrames,numCandidates);
    frameUndetected=zeros(numFrames,numCandidates);
    pilotScheduleExpected=mimo_ofdm_pilot_schedule(nSymbols,cfg.system.nTx,pilotSpacing);
    nBlocksExpected=numel(pilotScheduleExpected.pilotOccasionStarts);
    blockRows=cell(numFrames*nBlocksExpected,1); blockRowIndex=0;

    for frameIndex=1:numFrames
      seedBase=cfg.simulation.randomSeed+1e7*c+1e6*p+1e5*d+1e4*is+100*frameIndex;
      params.nSymbols=nSymbols; params.pilotSpacing=pilotSpacing; params.pilotSNRdB=snrDb;
      params.maxDopplerHz=fd; params.txRho=profileRhos(p,1); params.rxRho=profileRhos(p,2);
      params.targetBER=targetBER; params.modulations=modulations; params.estimator='jakes-lmmse';
      params.dataSeed=seedBase+1; params.pilotSeed=seedBase+2;
      params.channelSeed=seedBase+3; params.noiseSeed=seedBase+4;
      frame=simulate_pilot_mapped_adaptive_frame_v15_2(cfg,channelName,params);
      for q=1:numCandidates
        candidate=frame.candidates{q};
        payloadErrors(frameIndex,q)=candidate.BitErrors;
        payloadBits(frameIndex,q)=candidate.TotalBits;
        codedErrors(frameIndex,q)=candidate.CodedBitErrors;
        codedBits(frameIndex,q)=candidate.TotalCodedBits;
        packetErrors(frameIndex,q)=candidate.PacketErrors;
        packetCounts(frameIndex,q)=candidate.PacketCount;
        frameErrors(frameIndex,q)=candidate.FrameError;
        frameGoodput(frameIndex,q)=candidate.CRCGoodput_bpsHz;
        frameBitGoodput(frameIndex,q)=candidate.BitGoodput_bpsHz;
        frameNetSE(frameIndex,q)=candidate.NetSpectralEfficiency_bpsHz;
        frameGrossSE(frameIndex,q)=candidate.GrossSpectralEfficiency_bpsHz;
        framePred(frameIndex,q)=candidate.PredictedBER;
        frameFeasible(frameIndex,q)=candidate.TargetFeasibleBlockRatio;
        frameSM(frameIndex,q)=candidate.SpatialMultiplexingFrameRatio;
        frameAL(frameIndex,q)=candidate.AlamoutiFrameRatio;
        frameQPSK(frameIndex,q)=candidate.QPSKFrameRatio;
        frameQAM16(frameIndex,q)=candidate.QAM16FrameRatio;
        framePost(frameIndex,q)=candidate.MeanPosteriorVariance;
        frameICI(frameIndex,q)=candidate.MeanEstimatedICINoiseVariance;
        frameNMSE(frameIndex,q)=candidate.NMSE;
        frameUndetected(frameIndex,q)=candidate.UndetectedPacketErrors;
      end
      for b=1:numel(frame.blocks)
        block=frame.blocks(b); ch=block.choice;
        blockRowIndex=blockRowIndex+1;
        blockRows{blockRowIndex}=table(string(channelName),string(profileName),fd,snrDb, ...
          frameIndex,b,block.dataIndices(1),block.dataIndices(end),string(ch.Mode), ...
          ch.ModulationOrder,ch.PredictedBER,ch.TargetFeasible, ...
          block.prediction.predictedBER(1,1),block.prediction.predictedBER(1,2), ...
          block.prediction.predictedBER(2,1),block.prediction.predictedBER(2,2), ...
          block.prediction.meanPosteriorVariance,block.iciNoiseVariance, ...
          'VariableNames',{'Channel','SpatialProfile','MaxDoppler_Hz','PilotSNR_dB', ...
          'FrameIndex','BurstIndex','FirstDataSymbol','LastDataSymbol','SelectedMode', ...
          'SelectedModulationOrder','PredictedBER','TargetFeasible', ...
          'PredBER_SM_QPSK','PredBER_SM_16QAM','PredBER_Alamouti_QPSK', ...
          'PredBER_Alamouti_16QAM','MeanPosteriorVariance','EstimatedICINoiseVariance'});
      end
    end

    % Build frame-level logs for each strategy/coding pair, then cluster-aware CIs.
    frameTables=cell(numCandidates,1);
    for q=1:numCandidates
      si=ceil(q/numel(codingModes)); ci=mod(q-1,numel(codingModes))+1;
      frameTables{q}=table(repmat(string(channelName),numFrames,1), ...
        repmat(string(profileName),numFrames,1),repmat(string(strategyNames{si}),numFrames,1), ...
        repmat(string(codingModes{ci}),numFrames,1),repmat(fd,numFrames,1), ...
        repmat(snrDb,numFrames,1),(1:numFrames).',payloadErrors(:,q),payloadBits(:,q), ...
        payloadErrors(:,q)./max(payloadBits(:,q),1),codedErrors(:,q),codedBits(:,q), ...
        codedErrors(:,q)./max(codedBits(:,q),1),packetErrors(:,q),packetCounts(:,q), ...
        packetErrors(:,q)./max(packetCounts(:,q),1),frameErrors(:,q),frameNetSE(:,q), ...
        frameGoodput(:,q),frameBitGoodput(:,q),framePred(:,q),frameFeasible(:,q), ...
        frameSM(:,q),frameAL(:,q),frameQPSK(:,q),frameQAM16(:,q), ...
        'VariableNames',{'Channel','SpatialProfile','Strategy','CodingMode','MaxDoppler_Hz', ...
        'PilotSNR_dB','FrameIndex','PayloadBitErrors','PayloadBits','PayloadBER', ...
        'CodedBitErrors','CodedBits','CodedBER','PacketErrors','PacketCount','PacketErrorRate', ...
        'FrameError','NetPayloadSE_bpsHz','CRCGoodput_bpsHz','BitGoodput_bpsHz', ...
        'PredictedBER','PredictedFeasibleDataRatio','SMDataRatio','AlamoutiDataRatio', ...
        'QPSKDataRatio','QAM16DataRatio'});

      totalPayloadErrors=sum(payloadErrors(:,q)); totalPayloadBits=sum(payloadBits(:,q));
      totalCodedErrors=sum(codedErrors(:,q)); totalCodedBits=sum(codedBits(:,q));
      totalPacketErrors=sum(packetErrors(:,q)); totalPackets=sum(packetCounts(:,q));
      totalFrameErrors=nnz(frameErrors(:,q));
      berMetric=bit_error_metrics(totalPayloadErrors,totalPayloadBits,totalPacketErrors,totalPackets);
      codedMetric=bit_error_metrics(totalCodedErrors,totalCodedBits,totalPacketErrors,totalPackets);
      perMetric=bit_error_metrics(totalPacketErrors,totalPackets,totalFrameErrors,numFrames);
      berCluster=cluster_bootstrap_ber_ci(payloadErrors(:,q),payloadBits(:,q), ...
        numBootstrap,confidenceLevel,cfg.statistics.bootstrapSeed+conditionNumber*1000+q);
      codedCluster=cluster_bootstrap_ber_ci(codedErrors(:,q),codedBits(:,q), ...
        numBootstrap,confidenceLevel,cfg.statistics.bootstrapSeed+conditionNumber*1000+100+q);
      perCluster=cluster_bootstrap_ber_ci(packetErrors(:,q),packetCounts(:,q), ...
        numBootstrap,confidenceLevel,cfg.statistics.bootstrapSeed+conditionNumber*1000+200+q);
      goodputCI=frame_bootstrap_mean_ci(frameGoodput(:,q),numBootstrap,confidenceLevel, ...
        cfg.statistics.bootstrapSeed+conditionNumber*1000+300+q);
      si=ceil(q/numel(codingModes)); ci=mod(q-1,numel(codingModes))+1;
      if strcmp(codingModes{ci},'conv-crc-1/2'), decoderName='max-log soft-decision Viterbi';
      else, decoderName='not used (uncoded packet)'; end
      row=table(string(channelName),string(profileName),profileRhos(p,1),profileRhos(p,2), ...
        fd,snrDb,pilotSpacing,targetBER,string(strategyNames{si}),string(codingModes{ci}), ...
        string(decoderName),frame.candidates{q}.CodeRate,mean(framePred(:,q)),mean(frameFeasible(:,q)), ...
        mean(frameSM(:,q)),mean(frameAL(:,q)),mean(frameQPSK(:,q)),mean(frameQAM16(:,q)), ...
        berMetric.BER,berMetric.BER_CI95_Lower,berMetric.BER_CI95_Upper,berCluster(1),berCluster(2), ...
        codedMetric.BER,codedMetric.BER_CI95_Lower,codedMetric.BER_CI95_Upper,codedCluster(1),codedCluster(2), ...
        perMetric.BER,perMetric.BER_CI95_Lower,perMetric.BER_CI95_Upper,perCluster(1),perCluster(2), ...
        totalFrameErrors/numFrames,mean(frameNetSE(:,q)),mean(frameGrossSE(:,q)), ...
        mean(frameBitGoodput(:,q)),mean(frameGoodput(:,q)),goodputCI(1),goodputCI(2), ...
        mean(framePost(:,q)),mean(frameICI(:,q)),mean(frameNMSE(:,q)), ...
        totalPayloadErrors,totalPayloadBits,totalCodedErrors,totalCodedBits, ...
        totalPacketErrors,totalPackets,sum(frameUndetected(:,q)),numFrames, ...
        'VariableNames',{'Channel','SpatialProfile','TxRho','RxRho','MaxDoppler_Hz', ...
        'PilotSNR_dB','PilotSpacingSymbols','TargetBER','Strategy','CodingMode','FECDecoder','CodeRate', ...
        'MeanPredictedBER','PredictedTargetFeasibleDataRatio','SpatialMultiplexingDataRatio', ...
        'AlamoutiDataRatio','QPSKDataRatio','QAM16DataRatio','PayloadBER', ...
        'PayloadBER_WilsonCI95_Lower','PayloadBER_WilsonCI95_Upper', ...
        'PayloadBER_FrameBootstrapCI95_Lower','PayloadBER_FrameBootstrapCI95_Upper', ...
        'CodedBER','CodedBER_WilsonCI95_Lower','CodedBER_WilsonCI95_Upper', ...
        'CodedBER_FrameBootstrapCI95_Lower','CodedBER_FrameBootstrapCI95_Upper', ...
        'PacketErrorRate','PER_WilsonCI95_Lower','PER_WilsonCI95_Upper', ...
        'PER_FrameBootstrapCI95_Lower','PER_FrameBootstrapCI95_Upper','FrameErrorRate', ...
        'MeanNetPayloadSE_bpsHz','MeanGrossSE_bpsHz','MeanBitGoodput_bpsHz', ...
        'MeanCRCGoodput_bpsHz','CRCGoodput_FrameBootstrapCI95_Lower', ...
        'CRCGoodput_FrameBootstrapCI95_Upper','MeanPosteriorVariance', ...
        'MeanEstimatedICINoiseVariance','MeanChannelNMSE','TotalPayloadBitErrors', ...
        'TotalPayloadBits','TotalCodedBitErrors','TotalCodedBits','TotalPacketErrors', ...
        'TotalPackets','UndetectedPacketErrors','NumFrames'});
      if isempty(results), results=row; else, results=[results;row]; end %#ok<AGROW>
    end
    frameLogParts{conditionNumber}=vertcat(frameTables{:});
    blockLogParts{conditionNumber}=vertcat(blockRows{1:blockRowIndex});
    fprintf('  Completed %d frames: adaptive UNC BER=%.3g | adaptive FEC payload BER=%.3g | FEC PER=%.3g\n', ...
      numFrames,results.PayloadBER(find(string(results.Channel)==channelName & ...
      string(results.SpatialProfile)==profileName & results.MaxDoppler_Hz==fd & ...
      results.PilotSNR_dB==snrDb & string(results.Strategy)=='adaptive' & ...
      string(results.CodingMode)=='uncoded-crc',1,'last')), ...
      results.PayloadBER(find(string(results.Channel)==channelName & ...
      string(results.SpatialProfile)==profileName & results.MaxDoppler_Hz==fd & ...
      results.PilotSNR_dB==snrDb & string(results.Strategy)=='adaptive' & ...
      string(results.CodingMode)=='conv-crc-1/2',1,'last')), ...
      results.PacketErrorRate(find(string(results.Channel)==channelName & ...
      string(results.SpatialProfile)==profileName & results.MaxDoppler_Hz==fd & ...
      results.PilotSNR_dB==snrDb & string(results.Strategy)=='adaptive' & ...
      string(results.CodingMode)=='conv-crc-1/2',1,'last')));
   end
  end
 end
end

frameLog=vertcat(frameLogParts{:}); blockLog=vertcat(blockLogParts{:});
outDir=fullfile(projectRoot,'pilot_mapped_results_v15_2_1');
if ~exist(outDir,'dir'), mkdir(outDir); end
writetable(results,fullfile(outDir,'adaptive_link_results_v15_2_1.csv'));
writetable(frameLog,fullfile(outDir,'adaptive_link_frame_log_v15_2_1.csv'));
writetable(blockLog,fullfile(outDir,'adaptive_link_block_decisions_v15_2_1.csv'));
save(fullfile(outDir,'adaptive_link_results_v15_2_1.mat'),'cfg','channelNames','profileNames', ...
 'profileRhos','dopplerValuesHz','pilotSNRValuesdB','pilotSpacing','nSymbols','modulations', ...
 'targetBER','numFrames','numBootstrap','confidenceLevel','strategyNames','codingModes', ...
 'results','frameLog','blockLog','-v7.3');
fprintf('\nV15.2.1 SOFT-DECISION FEC VALIDATION COMPLETED\n');
fprintf('Frames/condition       : %d\n',numFrames);
fprintf('Summary rows           : %d (expected %d)\n',height(results),conditionCount*numCandidates);
fprintf('Frame log rows         : %d (expected %d)\n',height(frameLog),conditionCount*numFrames*numCandidates);
fprintf('Burst decision rows    : %d (expected %d)\n',height(blockLog),conditionCount*numFrames*nBlocksExpected);
fprintf('Output                 : %s\n',outDir);
end
