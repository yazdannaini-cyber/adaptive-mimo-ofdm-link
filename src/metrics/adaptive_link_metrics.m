function stats = adaptive_link_metrics(framePredictedBER, framePayloadBits, ...
        frameTargetFeasible, frameFallback, measuredBER, measuredBERUpper95, targetBER)
%ADAPTIVE_LINK_METRICS Clearly separate predictions, feasibility and outcomes.
% Frame predictions are averaged both equally per frame and weighted by the
% actual payload-bit count, so they can be compared fairly with aggregate BER.

framePredictedBER = framePredictedBER(:);
framePayloadBits = framePayloadBits(:);
frameTargetFeasible = logical(frameTargetFeasible(:));
frameFallback = logical(frameFallback(:));
n = numel(framePredictedBER);
if n == 0 || numel(framePayloadBits) ~= n || ...
        numel(frameTargetFeasible) ~= n || numel(frameFallback) ~= n || ...
        any(~isfinite(framePredictedBER)) || any(framePredictedBER < 0) || ...
        any(framePredictedBER > 0.5) || any(~isfinite(framePayloadBits)) || ...
        any(framePayloadBits <= 0) || ~isscalar(measuredBER) || ...
        ~isfinite(measuredBER) || measuredBER < 0 || measuredBER > 1 || ...
        ~isscalar(measuredBERUpper95) || ~isfinite(measuredBERUpper95) || ...
        measuredBERUpper95 < measuredBER || measuredBERUpper95 > 1 || ...
        ~isscalar(targetBER) || ~isfinite(targetBER) || targetBER <= 0 || targetBER >= 0.5
    error('adaptive_link_metrics:InvalidInput','Invalid adaptive frame or BER statistics.');
end

stats.MeanPredictedBER_FrameAverage = mean(framePredictedBER);
stats.PredictedBER_PayloadWeighted = ...
    sum(framePredictedBER .* framePayloadBits) / sum(framePayloadBits);
stats.PredictedTargetMetFrameRatio = mean(frameTargetFeasible);
stats.FallbackQPSKFrameRatio = mean(frameFallback);
stats.ObservedBER_TargetSatisfied = measuredBER <= targetBER;
stats.ObservedBER_CI95UpperBelowTarget = measuredBERUpper95 <= targetBER;
stats.TotalPayloadBits = sum(framePayloadBits);
end
